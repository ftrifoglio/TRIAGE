# should take the interaction dataframe (as passed to `save_adjacency`), the reference
# split directory, `test_ratio`, and the timestamp column name, and output a mapping
# with the total recall misses and the counts for each reason. The reasons should add up
# to the total. If the function is too long create helper functions. Denote helper
# functions only used by this function with an underscore prefix. As for the reasons, a
# miss can either be due to ties at the boundary where train and test split, or just a
# different preprocessing that creates very different item sets, or the item sets are
# the same but their ordering is not temporal `(timestamp, item)`. Check the reasons in
# that order: a miss is a tie if it has the same timestamp as the user's last train
# edge, even if the item sets differ.
def log_recall_miss_diagnostic(
    df: pd.DataFrame,
    ref_dir: Path,
    test_ratio: float,
    time_col: str = "timestamp",
) -> dict[str, int] | None:
    """
    Attribute a recall miss against a reference split.

    A recall miss is a reference test edge that our split puts in train.

    A miss is labelled as:
    - `tie_recoverable` if the missed edge has the same timestamp as the user's last
      train edge (a minor miss as ordering the tied edges another way could recover it).
    - `core_surplus` if it's not `tie_recoverable` and the user's item set differs from
      their item set in the reference (a preprocessing difference, not from ordering).
    - `order_divergence` if neither of the above (an ordering difference).

    Parameters
    ----------
    df : pd.DataFrame
        Interaction frame with `user`, `item`, and `time_col` columns, taken at the same
        point the splitter consumes it (post dedupe + k-core), with original IDs.
    ref_dir : Path
        Reference split directory (`user_list.txt`, `item_list.txt`, `train.txt`,
        `test.txt`) to attribute misses against.
    test_ratio : float
        Fraction of each user's interactions held out, matching `save_adjacency`.
    time_col : str, default "timestamp"
        Name of the timestamp column ordered on; matched to the splitter.

    Returns
    -------
    dict[str, int] | None
        Keys `recall_miss`, `tie_recoverable`, `core_surplus`, and `order_divergence`,
        or None if the reference splits are absent.

    """
    if not ref_dir.exists():
        print(f"  no reference splits at {ref_dir} - skipping recall-miss diagnostic")
        return None

    ref_test = load_test_edges(ref_dir)
    _, _, ref_edges = load_splits(ref_dir)
    ref_items_by_user: dict = {}
    for u, it in ref_edges:
        ref_items_by_user.setdefault(u, set()).add(it)

    work = _per_edge_split(df, test_ratio, time_col)
    users = work["user"].to_numpy()
    items = work["item"].to_numpy()
    is_test = work["is_test"].to_numpy()
    on_boundary = work["on_boundary"].to_numpy()

    our_test = set(zip(users[is_test], items[is_test]))
    bnd = ~is_test & on_boundary
    boundary_train = set(zip(users[bnd], items[bnd]))
    our_items_by_user: dict = {}
    for u, it in zip(users, items):
        our_items_by_user.setdefault(u, set()).add(it)

    missed = ref_test - our_test
    tie_recoverable = missed & boundary_train
    structural = missed - tie_recoverable
    core_surplus = {
        (u, it)
        for u, it in structural
        if our_items_by_user.get(u, set()) != ref_items_by_user.get(u, set())
    }
    order_divergence = structural - core_surplus

    n_miss = len(missed)

    def _pct(x: int) -> str:
        return f"({100 * x / max(n_miss, 1):.1f}%)"

    print(f"\nrecall-miss diagnostic vs {ref_dir.name} (test_ratio={test_ratio}):")
    print(f"  {'reference test edges we miss (in train)':<44} : {n_miss:>10,}")
    print(
        f"  {'tie-recoverable (share train boundary ts)':<44} : "
        f"{len(tie_recoverable):>10,}  {_pct(len(tie_recoverable))}"
    )
    print(
        f"  {'core-surplus (user item set differs)':<44} : "
        f"{len(core_surplus):>10,}  {_pct(len(core_surplus))}"
    )
    print(
        f"  {'order-divergence (same item set, diff order)':<44} : "
        f"{len(order_divergence):>10,}  {_pct(len(order_divergence))}"
    )

    return {
        "recall_miss": n_miss,
        "tie_recoverable": len(tie_recoverable),
        "core_surplus": len(core_surplus),
        "order_divergence": len(order_divergence),
    }


def _per_edge_split(
    df: pd.DataFrame,
    test_ratio: float,
    time_col: str,
) -> pd.DataFrame:
    """
    Re-derive the per-user temporal leave-last-out split, edge by edge.

    Mirrors `save_adjacency` exactly: order each user by `(timestamp, item)` (item order
    == remapped-index order == sorted-original-id order), hold out the `ceil(test_ratio
    * n)` most recent as test. Also flags whether each edge shares its user's latest
    retained-train timestamp (`on_boundary`), i.e. whether a different tie-break could
    have moved it across the split.

    Parameters
    ----------
    df : pd.DataFrame
        Interaction frame with `user`, `item`, and `time_col` columns, taken at the same
        point the splitter consumes it (post dedupe + k-core).
    test_ratio : float
        Fraction of each user's interactions held out, matching `save_adjacency`.
    time_col : str
        Name of the timestamp column ordered on.

    Returns
    -------
    pd.DataFrame
        Columns `user`, `item`, `is_test` (bool), `on_boundary` (bool), in the
        splitter's per-user order.

    """
    work = pd.DataFrame(
        {
            "user": df["user"].to_numpy(),
            "item": df["item"].to_numpy(),
            "t": pd.factorize(df[time_col], sort=True)[0],
        }
    ).sort_values(["user", "t", "item"], kind="stable")

    grp = work.groupby("user", sort=True)
    n = grp["t"].transform("size").to_numpy()
    pos = grp.cumcount().to_numpy()
    n_test = np.where(n >= 2, np.maximum(1, np.ceil(n * test_ratio)).astype(int), 0)
    is_test = pos >= (n - n_test)

    tc = work["t"].to_numpy()
    train_code = np.where(is_test, -1, tc)
    max_train = (
        pd.Series(train_code, index=work["user"].to_numpy())
        .groupby(level=0)
        .transform("max")
        .to_numpy()
    )
    work["is_test"] = is_test
    work["on_boundary"] = tc == max_train
    return work


