"""Logging helpers used by `scripts/*.py`."""

from pathlib import Path

import numpy as np
import pandas as pd

from .io import load_splits, load_test_edges


def log_stage(label: str, df: pd.DataFrame) -> None:
    """
    Print a one-line summary: |interactions, users, items| for a stage.

    Parameters
    ----------
    label : str
        Stage label printed at the start of the line.
    df : pd.DataFrame
        Interaction frame with `user` and `item` columns to summarise.

    """
    print(
        f"{label:<22} : "
        f"{len(df):>10,} interactions  "
        f"({df['user'].nunique():>6,} users, "
        f"{df['item'].nunique():>6,} items)"
    )


def log_final_vs_expected(df: pd.DataFrame, expected: dict[str, int]) -> None:
    """
    Print final stats next to expected values for verification.

    Parameters
    ----------
    df : pd.DataFrame
        Interaction frame with `user` and `item` columns.
    expected : dict[str, int]
        Reference values keyed by `users`, `items`, and `interactions`.

    """
    n_users = df["user"].nunique()
    n_items = df["item"].nunique()
    n_inter = len(df)
    density = n_inter / max(n_users * n_items, 1)
    e_density = expected["interactions"] / max(expected["users"] * expected["items"], 1)

    table = pd.DataFrame(
        {
            "expected": [
                f"{expected['users']:,}",
                f"{expected['items']:,}",
                f"{expected['interactions']:,}",
                f"{e_density * 100:.4f}%",
            ],
            "ours": [
                f"{n_users:,}",
                f"{n_items:,}",
                f"{n_inter:,}",
                f"{density * 100:.4f}%",
            ],
        },
        index=["users", "items", "interactions", "density"],
    )
    print("\nfinal vs expected:")
    print(table.to_string())


def log_pr_vs_reference(df: pd.DataFrame, splits_dir: Path) -> None:
    """
    Print recall and precision of users / items / edges against a reference.

    Parameters
    ----------
    df : pd.DataFrame
        Interaction frame with `user` and `item` columns to evaluate.
    splits_dir : Path
        Directory of reference split files loaded via `load_splits`.

    """
    if not splits_dir.exists():
        print(f"  no reference splits at {splits_dir} - skipping recall")
        return

    ref_users, ref_items, ref_edges = load_splits(splits_dir)
    our_users = set(df["user"])
    our_items = set(df["item"])
    our_edges = set(zip(df["user"], df["item"]))

    print(f"\nrecall / precision vs {splits_dir.name}:")
    for label, ours, ref in [
        ("users", our_users, ref_users),
        ("items", our_items, ref_items),
        ("edges", our_edges, ref_edges),
    ]:
        hit = len(ours & ref)
        recall = hit / max(len(ref), 1)
        precision = hit / max(len(ours), 1)
        print(
            f"  {label:<5} : recall={recall:.4f}  precision={precision:.4f}  "
            f"(hit={hit:>10,}  ref={len(ref):>10,}  ours={len(ours):>10,})"
        )


def log_test_split_parity(out_dir: Path, ref_dir: Path) -> None:
    """
    Print test-edge recall / precision of the written test split vs reference.

    Parameters
    ----------
    out_dir : Path
        Directory of the just-written split (`user_list.txt`, `item_list.txt`,
        `test.txt`).
    ref_dir : Path
        Reference split directory to compare against.

    """
    if not ref_dir.exists():
        print(f"  no reference splits at {ref_dir} - skipping test-split parity")
        return

    our_test = load_test_edges(out_dir)
    ref_test = load_test_edges(ref_dir)
    hit = len(our_test & ref_test)
    recall = hit / max(len(ref_test), 1)
    precision = hit / max(len(our_test), 1)

    print(f"\ntest-split parity vs {ref_dir.name}:")
    print(
        f"  test edges : recall={recall:.4f}  precision={precision:.4f}  "
        f"(hit={hit:>10,}  ref={len(ref_test):>10,}  ours={len(our_test):>10,})"
    )


