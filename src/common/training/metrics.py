"""Metric functions used by `Evaluator`."""

import numpy as np
import torch
from scipy.stats import rankdata


def recall_at_k(hits: torch.Tensor, n_pos: torch.Tensor) -> torch.Tensor:
    """
    Compute per-user Recall@K as the fraction of a user's positives found in the top K.

    Parameters
    ----------
    hits : torch.Tensor of shape (n_chunk_users, K), bool
        Hit indicator of the top-K items, best first.
    n_pos : torch.Tensor of shape (n_chunk_users,), int64
        Number of positives per user.

    Returns
    -------
    torch.Tensor of shape (n_chunk_users,), float32
        Per-user recall; `0` for users without positives.

    """
    return hits.sum(dim=-1).float() / n_pos.clamp(min=1).float()


def ndcg_at_k(hits: torch.Tensor, n_pos: torch.Tensor) -> torch.Tensor:
    """
    Compute per-user NDCG@K with binary relevance.

    The DCG discounts each hit at rank `r` (1-based) by `1 / log2(r + 1)`. The IDCG is
    the DCG of a list whose first `min(n_pos, K)` items are all hits.

    Parameters
    ----------
    hits : torch.Tensor of shape (n_chunk_users, K), bool
        Hit indicator of the top-K items, best first.
    n_pos : torch.Tensor of shape (n_chunk_users,), int64
        Number of positives per user.

    Returns
    -------
    torch.Tensor of shape (n_chunk_users,), float32
        Per-user NDCG; `0` for users without positives.

    """
    k = hits.shape[1]
    discounts = 1.0 / torch.log2(torch.arange(2, k + 2, device=hits.device).float())
    dcg = (hits.float() * discounts).sum(dim=-1)
    # IDCG for each possible number of hits m = 0..K, to be looked up per user
    idcg_by_m = torch.stack([discounts[:m].sum() for m in range(k + 1)])
    idcg = idcg_by_m[n_pos.clamp(max=k)]
    return torch.where(idcg > 0, dcg / idcg, torch.zeros_like(dcg))


def self_information(deg: torch.Tensor, n_users: int) -> torch.Tensor:
    """
    Compute the normalised self-information `-log2(deg / n_users) / log2(n_users)`.

    Parameters
    ----------
    deg : torch.Tensor of any shape, float64
        Training degrees of the recommended items.
    n_users : int
        Number of users in the dataset.

    Returns
    -------
    torch.Tensor of the same shape as deg, float64
        Self-information per item; `inf` where `deg == 0`, which the caller excludes
        from the novelty mean.

    """
    # https://github.com/fuxiAIlab/r-AdjNorm/blob/6b6edd3/src/utility/batch_test.py#L259
    n = float(n_users)
    log2_n = float(np.log2(n)) if n > 1 else 1.0
    return -torch.log2(deg / n) / log2_n


def item_coverage(rec_counts: torch.Tensor, n_items: int) -> float:
    """
    Compute the fraction of the catalogue recommended to at least one user.

    Parameters
    ----------
    rec_counts : torch.Tensor of shape (n_items,), float32
        Number of top-K lists each item appears in.
    n_items : int
        Catalogue size.

    Returns
    -------
    float
        Item coverage in `[0, 1]`.

    """
    return float((rec_counts > 0).sum().item()) / n_items


def effective_coverage(rec_counts: torch.Tensor, n_items: int) -> float:
    """
    Compute `exp(H) / n_items`, with `H` the entropy of the recommendation frequencies.

    Always `<= item_coverage`. Unlike item coverage, it penalises exposure concentrated
    on a few items even when many items are recommended at least once.

    Parameters
    ----------
    rec_counts : torch.Tensor of shape (n_items,), float32
        Number of top-K lists each item appears in.
    n_items : int
        Catalogue size.

    Returns
    -------
    float
        Effective coverage in `(0, 1]`; `0` when nothing was recommended.

    """
    total = rec_counts.sum()
    if total <= 0:
        return 0.0
    p = rec_counts[rec_counts > 0] / total
    entropy = -(p * p.log()).sum()
    return float(torch.exp(entropy).item()) / n_items


