def pru_plus(
    scores: torch.Tensor, gt: torch.Tensor, pop_np: np.ndarray, chunk: int
) -> np.ndarray:
    """
    Compute per-user SRC of ground-truth scores and their degrees in the full list.

    Sets the rank to the number of items that score strictly higher. Groups users by
    how many ground-truth items they have. It ranks each group with one rankdata call.
    Computes each user's Pearson on those ranks.

    Parameters
    ----------
    scores : torch.Tensor of shape (n_chunk_users, n_items), float32 or float64
        Masked scores of the chunk; masked items are `-inf`. float64 after popularity
        compensation.
    gt : torch.Tensor of shape (n_chunk_users, n_items), bool
        Ground-truth indicator of the chunk.
    pop_np : np.ndarray of shape (n_items,), float64
        Training degree of every item.
    chunk : int
        Number of gt cells ranked per block.

    Returns
    -------
    np.ndarray of shape (n_chunk_users,), float64
        Per-user SRC; `NaN` for users with fewer than two ground-truth items, or whose
        ground-truth items all share the same popularity or the same score.

    """
    out = np.full(gt.shape[0], np.nan)
    gt_rc = gt.nonzero(as_tuple=False)  # (T, 2), row-major (row, col)
    if not gt_rc.numel():
        return out
    rows, cols = gt_rc[:, 0], gt_rc[:, 1]
    gt_pops = pop_np[cols.cpu().numpy()]
    counts = gt.sum(dim=1).cpu().numpy()
    gt_scores = scores[rows, cols]  # (T,) score per gt cell
    ranks_t = scores.new_empty(gt_rc.shape[0])
    for s in range(0, gt_rc.shape[0], chunk):
        rb = rows[s : s + chunk]
        ranks_t[s : s + chunk] = (
            (scores[rb] > gt_scores[s : s + chunk, None]).sum(dim=1).to(scores.dtype)
        )
    ranks = ranks_t.to(torch.float64).cpu().numpy()
    offs = np.cumsum(counts) - counts
    for cnt in np.unique(counts[counts >= 2]):
        us = np.flatnonzero(counts == cnt)
        cells = offs[us, None] + np.arange(cnt)
        rp = rankdata(gt_pops[cells], axis=1)
        rr = rankdata(ranks[cells], axis=1)
        for j, u in enumerate(us):
            out[u] = _pearson_of_ranks(rp[j], rr[j])
    return out


