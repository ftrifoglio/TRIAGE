def pru_at_k(top_idx: torch.Tensor, pop_np: np.ndarray, k: int) -> np.ndarray:
    """
    Compute per-user SRC between all positions and their degrees in a top-k list.

    Positions `0..K-1` are ranked once, and every user's popularity row is ranked in one
    call. Loop Pearson correlation over users.

    Parameters
    ----------
    top_idx : torch.Tensor of shape (n_chunk_users, max_k), int64
        Top-`max_k` item idx of the chunk, best first.
    pop_np : np.ndarray of shape (n_items,), float64
        Training degree of every item.
    k : int
        Cut-off K.

    Returns
    -------
    np.ndarray of shape (n_chunk_users,), float64
        Per-user SRC. A constant-popularity row gets `1e-15` added to its last degree,
        as in the reference, so its SRC is finite when the degree is below 16 and `NaN`
        from 16 up, where float64 absorbs the addition.

    """
    top_pops = pop_np[top_idx[:, :k].cpu().numpy()]  # (n_chunk_users, k)
    tied = np.all(top_pops == top_pops[:, :1], axis=1)
    top_pops[tied, -1] += 1e-15
    r_pos = rankdata(np.arange(k, dtype=np.float64))
    r_pops = rankdata(top_pops, axis=1)
    return np.array([_pearson_of_ranks(r_pos, r_pops[b]) for b in range(len(r_pops))])


def _pearson_of_ranks(rx: np.ndarray, ry: np.ndarray) -> float:
    """
    Pearson correlation of two rank vectors: Spearman's rho once both are ranked.

    The PRU loops rank many rows in one `rankdata(..., axis=1)` call (average ranks for
    ties, the same values as ranking each row alone) and reduce each row here, in the
    original order, so the batching changes where the ranks are computed and not the
    arithmetic on them.

    Parameters
    ----------
    rx : np.ndarray of shape (n,), float64
        Ranks of the first variable, with `n >= 2`.
    ry : np.ndarray of shape (n,), float64
        Ranks of the second variable.

    Returns
    -------
    float
        The correlation, or `NaN` when either variable is constant (undefined
        correlation).

    """
    rx = rx - rx.mean()
    ry = ry - ry.mean()
    denom = np.sqrt((rx @ rx) * (ry @ ry))
    if denom == 0:
        return float("nan")
    return float((rx @ ry) / denom)
