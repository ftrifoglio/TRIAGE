    # `torch.sparse.mm(adj, x)`'s backward computes `adj.t() @ grad`. For a CSR `adj`,
    # `.t()` only relabels the same arrays as CSC, but `mm` has no CSC kernel
    # (https://github.com/pytorch/pytorch/blob/70d99e9/aten/src/ATen/native/sparse/SparseCsrTensorMath.cpp#L775-L778)
    # and converts back to CSR: expand to COO, sort all nonzeros, recompress. Nothing is
