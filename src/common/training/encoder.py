"""LightGCN encoder and its SimGCL noise-perturbed variant."""

import torch
import torch.nn as nn

from .spmm import adj_mm


class LightGCNEncoder(nn.Module):
    """
    Layer-mean LightGCN encoder.

    No transformations, no activations, no self-loops -- verbatim Equation (8) of He et
    al., 2020. The propagation adjacency `adj` is supplied per-call so a
    `NeighbourhoodSampler` can shape it.
    """

    def __init__(
        self, n_users: int, n_items: int, emb_dim: int, n_layers: int, readout_ego: bool
    ) -> None:
        """
        Build the encoder and Xavier-initialise the joint embedding table.

        Parameters
        ----------
        n_users : int
            Number of users; the user block of the embedding table.
        n_items : int
            Number of items; the item block of the embedding table.
        emb_dim : int
            Embedding dimension `d`.
        n_layers : int
            Number of propagation layers `L`.
        readout_ego : bool
            Whether the layer-mean readout includes the layer-0 table. `True` averages
            layers `0..K`, `False` layers `1..K`.

        """
        super().__init__()
        self.n_users = n_users
        self.n_items = n_items
        self.n_layers = n_layers
        self.readout_ego = readout_ego
        self.embedding = nn.Embedding(n_users + n_items, emb_dim)
        nn.init.xavier_uniform_(self.embedding.weight)

    def initial_table(self) -> torch.Tensor:
        """
        Return the layer-0 joint user+item embedding matrix.

        Returns
        -------
        torch.Tensor of shape (n_users + n_items, d), float32
            The embedding weight E^(0).

        """
        return self.embedding.weight

    # Code generated by claude-opus-4-8 using prompt: I'd like a performance improvement
